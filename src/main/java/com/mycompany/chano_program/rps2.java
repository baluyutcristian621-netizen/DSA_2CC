    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if (health1 <= 0 || health2 <= 0) {
        return;
    }

    int p1, p2;

    try {
        p1 = Integer.parseInt(jTextField1.getText().trim());
        p2 = Integer.parseInt(jTextField2.getText().trim());
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Numero lang (1, 2, o 3) ang ilagay!");
        return;
    }

    if (p1 < 1 || p1 > 3 || p2 < 1 || p2 > 3) {
        javax.swing.JOptionPane.showMessageDialog(this, "1 = Rock, 2 = Paper, 3 = Scissor lang!");
        return;
    }

    String[] pili = {"", "ROCK", "PAPER", "SCISSOR"};
    String resulta = "";

     if (p1 == p2) {
         resulta = "DRAW GAME !";
     } else if ((p1 == 1 && p2 == 3) ||
                (p1 == 2 && p2 == 1) ||
                (p1 == 3 && p2 == 2)) {
         health2--;
         resulta = "PLAYER 1 WINS";
     } else {
         health1--;
         resulta = "PLAYER 2 WINS";
     }

     // I-update ang health labels
     jLabel6.setText("HEALTH: " + health1);
     jLabel7.setText("HEALTH: " + health2);
     if (health1 <= 0){
         lblWinner.setText("Player 2 Wins");
         jButton1.setEnabled(false);
     }
     else if(health2 <= 0){
         lblWinner.setText("Player 1 Wins");
         jButton1.setEnabled(false);
     }
     else{
         lblWinner.setText(resulta);
     }
    jTextField1.setText("");
    jTextField2.setText("");
    
    }//GEN-LAST:event_jButton1ActionPerformed

