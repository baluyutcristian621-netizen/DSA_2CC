    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         total = 0;
 
        if (jCheckBox1.isSelected()) {
            total += burgerPrice * (int) jSpinner4.getValue();
        }
        if (jCheckBox2.isSelected()) {
            total += friesPrice * (int) jSpinner5.getValue();
        }
        if (jCheckBox3.isSelected()) {
            total += sandwichPrice * (int) jSpinner6.getValue();
        }
        if (jCheckBox4.isSelected()) {
            total += waterPrice * (int) jSpinner1.getValue();
        }
        if (jCheckBox5.isSelected()) {
            total += lemonPrice * (int) jSpinner2.getValue();
        }
        if (jCheckBox6.isSelected()) {
            total += coffeePrice * (int) jSpinner3.getValue();
        }
 
        jTextField1.setText(String.format("%.2f", total));
    
    
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {
            double pay = Double.parseDouble(jTextField2.getText());
            double change = pay - total;
 
            if (change < 0) {
                JOptionPane.showMessageDialog(this, "Insufficient payment!", "Error", JOptionPane.ERROR_MESSAGE);
            } else {
                jTextField3.setText(String.format("%.2f", change));
                JOptionPane.showMessageDialog(this, "Payment successful!\nChange: \u20B1" + String.format("%.2f", change));
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid amount for Pay.", "Input Error", JOptionPane.WARNING_MESSAGE);
        }     
    }//GEN-LAST:event_jButton2ActionPerformed

