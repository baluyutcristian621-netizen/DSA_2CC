    private void btncancelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncancelActionPerformed
    // Check whether any field contains input
   boolean hasInput =
!txtusername.getText().trim().isEmpty()
|| txtpassword.getPassword().length > 0
|| !txtfirstname.getText().trim().isEmpty()
|| !txtlastname.getText().trim().isEmpty()
|| !txtage1.getText().trim().isEmpty()
|| !txtcourse1.getText().trim().isEmpty()
|| !txtsection.getText().trim().isEmpty();

// Ask for confirmation only if the Admin entered information
if (hasInput) {
    int confirm = JOptionPane.showConfirmDialog(
            this,
            "This record has not been saved.\n"
            + "Are you sure you want to cancel and discard your input?",
            "Unsaved Record",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
    );

    if (confirm == JOptionPane.YES_OPTION) {
        dispose();
    }
} else {
    // No input entered, so close directly
    dispose();
}
        
    }//GEN-LAST:event_btncancelActionPerformed

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
    String username = txtusername.getText().trim();
    String password = new String(txtpassword.getPassword());
    String firstname = txtfirstname.getText().trim();
    String lastname = txtlastname.getText().trim();
    String age = txtage1.getText().trim();
    String course = txtcourse1.getText().trim();
    String section = txtsection.getText().trim();

    if (username.isEmpty() || password.isEmpty()
            || firstname.isEmpty() || lastname.isEmpty()
            || age.isEmpty() || course.isEmpty()
            || section.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.");
        return;
    }

    String sql = "INSERT INTO user "
            + "(username, password, firstname, lastname, age, course, section) "
            + "VALUES (?, ?, ?, ?, ?, ?, ?)";

    try {
        if (conn == null || conn.isClosed()) {
            JOptionPane.showMessageDialog(this,
                    "Database connection is not available.");
            return;
        }

        int studentAge = Integer.parseInt(age);

        try (PreparedStatement pst = conn.prepareStatement(sql)) {
            pst.setString(1, username);
            pst.setString(2, password);
            pst.setString(3, firstname);
            pst.setString(4, lastname);
            pst.setInt(5, studentAge);
            pst.setString(6, course);
            pst.setString(7, section);

            pst.executeUpdate();
        }

        JOptionPane.showMessageDialog(this,
                "Student added successfully!");
        

        // Refresh the Admin JTable
      if (admin != null) {
        admin.loadUsers();
      }

        // Clear all fields
        txtusername.setText("");
        txtpassword.setText("");
        txtfirstname.setText("");
        txtlastname.setText("");
        txtage1.setText("");
        txtcourse1.setText("");
        txtsection.setText("");

        // Close the Add Student form
        dispose();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Age must be a valid number.");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error saving student: " + e.getMessage());
    }      
    }//GEN-LAST:event_btnsaveActionPerformed

