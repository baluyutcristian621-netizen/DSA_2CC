    private void btnVSActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVSActionPerformed


        int p1  = Integer.parseInt(txt1.getText());
        int p2  = Integer.parseInt(txt2.getText());
        
        if(p1 == 1 && p2 == 1)
        {
         JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.WARNING_MESSAGE);      
        }
        else if (p1 == 1 && p2 == 2)
        {
         JOptionPane.showMessageDialog(rootPane, "PLAYER 2 WINS", "RPS", JOptionPane.ERROR_MESSAGE );
        }
        else if(p1 == 1 && p2 == 3)
        {
        JOptionPane.showMessageDialog(rootPane, "PLAYER 1 WINS", "RPS", JOptionPane.ERROR_MESSAGE);   
        }
        else if(p1 == 2 && p2 == 1)
        {
         JOptionPane.showMessageDialog(rootPane, "PLAYER 1 WINS", "RPS", JOptionPane.ERROR_MESSAGE);
        }
        else if(p1 == 2 && p2 == 2)
        {
        JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.WARNING_MESSAGE);   
        }
        else if(p1 == 2 && p2 == 3)
        {
         JOptionPane.showMessageDialog(rootPane, "PLAYER 2 WINS", "RPS", JOptionPane.ERROR_MESSAGE);
        }
         else if(p1 == 3 && p2 == 1)
        {
         JOptionPane.showMessageDialog(rootPane, "PLAYER 2 WINS", "RPS", JOptionPane.ERROR_MESSAGE);
        }
        else if(p1 == 3 && p2 == 2)
        {
        JOptionPane.showMessageDialog(rootPane, "PLAYER 1 WINS", "RPS", JOptionPane.WARNING_MESSAGE);   
        }
        else if(p1 == 3 && p2 == 3)
        {
         JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnVSActionPerformed

